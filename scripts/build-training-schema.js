// Regenerates the Course / VideoObject structured data on zoho-books-training.html from the
// lesson markup itself, so the JSON-LD can never drift from what the page shows.
//
//   node scripts/build-training-schema.js
//
// Replaces the block between the training-schema markers in the <head> (on first run, the
// hand-written Course block). The working-tree file is CRLF; matching is done on LF.
const fs = require('fs');
const lib = require('./training-lib.js');
const MODULES = require('./training-modules.js');

let s = lib.readHub();
const all = lib.lessons(s);

const modules = MODULES.map(mod => {
  const own = all.filter(l => l.module === mod.n);
  return { '@type': 'Course', name: `Module ${mod.n}: ${lib.decode(mod.title)}`, description: lib.decode(mod.metaDescription),
    url: `${lib.SITE}/${mod.slug}`, provider: lib.provider, isAccessibleForFree: true, hasPart: lib.schemaParts(own) };
});

const videoSecs = all.filter(l => l.vid).reduce((a, l) => a + l.meta.seconds, 0);
const course = {
  '@context': 'https://schema.org', '@type': 'Course', '@id': `${lib.SITE}/zoho-books-training#course`,
  name: 'Zoho Books Training Course — India Edition',
  description: `Free Zoho Books training course, India edition: ${MODULES.length} modules and ${all.length} lessons on GST, e-invoicing, GSTR filing, TDS, banking, reports and automation, curated and audited by a CA firm.`,
  url: `${lib.SITE}/zoho-books-training`, provider: lib.provider,
  isAccessibleForFree: true, inLanguage: 'en-IN', educationalLevel: 'Beginner to intermediate',
  audience: { '@type': 'EducationalAudience', educationalRole: 'Accounting staff, freshers and CA firm teams' },
  offers: { '@type': 'Offer', price: '0', priceCurrency: 'INR', category: 'Free' },
  hasCourseInstance: { '@type': 'CourseInstance', courseMode: 'Online', courseWorkload: `PT${Math.round(videoSecs / 3600)}H` },
  dateModified: new Date().toISOString().slice(0, 10),
  hasPart: modules.concat([{ '@type': 'Course', name: 'Accounting Fundamentals for Freshers', url: `${lib.SITE}/zoho-books-training#module-20`, provider: lib.provider, isAccessibleForFree: true }])
};

const block = `<!-- training-schema:start (generated by scripts/build-training-schema.js — do not hand-edit) -->\n<script type="application/ld+json">${JSON.stringify(course)}</script>\n<!-- training-schema:end -->`;
const marker = /<!-- training-schema:start[\s\S]*?<!-- training-schema:end -->/;
if (marker.test(s)) s = s.replace(marker, block);
else {
  const old = /<script type="application\/ld\+json">\{"@context":"https:\/\/schema\.org","@type":"Course"[^\n]*<\/script>/;
  if (!old.test(s)) throw new Error('Course JSON-LD block not found');
  s = s.replace(old, block);
}
fs.writeFileSync(lib.HUB, s.replace(/\n/g, '\r\n'), 'utf8');
console.log(`schema: ${all.length} lessons (${all.filter(l => l.vid).length} VideoObject, ${all.filter(l => l.doc).length} LearningResource), ${modules.length} module Courses, ${(block.length / 1024).toFixed(1)} KB`);
